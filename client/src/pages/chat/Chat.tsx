import { useState } from "react";
import {
  ArrowUp,
  FileText,
  Menu,
  Sparkles,
} from "lucide-react";

interface Source {
  id: string;
  filename: string;
  page?: number;
  snippet?: string;
}

interface Message {
  id: string;
  role: "user" | "assistant";
  content: string;
  sources?: Source[];
}

const initialMessages: Message[] = [
  {
    id: "1",
    role: "assistant",
    content:
      "Hello! Ask me anything about the documents in your knowledge base.",
  },
];

export default function Chat() {
  const [messages, setMessages] =
    useState<Message[]>(initialMessages);

  const [input, setInput] = useState("");
  const [isLoading, setIsLoading] = useState(false);

  const handleSubmit = async (
    event: React.FormEvent
  ) => {
    event.preventDefault();

    const question = input.trim();

    if (!question || isLoading) return;

    const userMessage: Message = {
      id: crypto.randomUUID(),
      role: "user",
      content: question,
    };

    setMessages((prev) => [...prev, userMessage]);
    setInput("");
    setIsLoading(true);

    try {
      /*
       * Connect this to your Express SSE endpoint.
       *
       * Example:
       *
       * const response = await fetch("/api/chat", {
       *   method: "POST",
       *   headers: {
       *     "Content-Type": "application/json",
       *   },
       *   body: JSON.stringify({
       *     message: question,
       *   }),
       * });
       *
       * Then consume the SSE stream.
       */

      await new Promise((resolve) =>
        setTimeout(resolve, 1200)
      );

      const assistantMessage: Message = {
        id: crypto.randomUUID(),
        role: "assistant",
        content:
          "This is where the answer generated by your RAG pipeline will appear. The response will be streamed from your Express backend.",
        sources: [
          {
            id: "source-1",
            filename: "product-documentation.pdf",
            page: 12,
            snippet:
              "The product supports document-based question answering using a knowledge base.",
          },
          {
            id: "source-2",
            filename: "api-reference.docx",
            page: 4,
            snippet:
              "The API provides endpoints for uploading and processing documents.",
          },
        ],
      };

      setMessages((prev) => [
        ...prev,
        assistantMessage,
      ]);
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="flex h-screen bg-[#fafafa] text-zinc-950">

      {/* Sidebar */}
      <ChatSidebar />

      {/* Chat */}
      <main className="flex min-w-0 flex-1 flex-col">

        {/* Header */}
        <header className="flex h-16 shrink-0 items-center border-b border-zinc-200 bg-white px-5">

          <button
            className="mr-3 flex h-9 w-9 items-center justify-center rounded-lg text-zinc-500 hover:bg-zinc-100 lg:hidden"
          >
            <Menu size={19} />
          </button>

          <div className="flex items-center gap-3">

            <div className="flex h-9 w-9 items-center justify-center rounded-lg bg-zinc-950 text-white">
              <FileText size={17} />
            </div>

            <div>
              <h1 className="text-sm font-semibold">
                Knowledge Base
              </h1>

              <p className="text-xs text-zinc-400">
                Document Assistant
              </p>
            </div>

          </div>

        </header>

        {/* Messages */}
        <div className="flex-1 overflow-y-auto">

          <div className="mx-auto w-full max-w-3xl px-5 py-10">

            {messages.map((message) => (
              <MessageBubble
                key={message.id}
                message={message}
              />
            ))}

            {isLoading && (
              <LoadingMessage />
            )}

          </div>

        </div>

        {/* Input */}
        <div className="shrink-0 bg-[#fafafa] px-5 pb-5">

          <form
            onSubmit={handleSubmit}
            className="mx-auto max-w-3xl"
          >

            <div className="relative rounded-2xl border border-zinc-300 bg-white shadow-sm focus-within:border-zinc-400">

              <textarea
                value={input}
                onChange={(e) =>
                  setInput(e.target.value)
                }
                onKeyDown={(e) => {
                  if (
                    e.key === "Enter" &&
                    !e.shiftKey
                  ) {
                    e.preventDefault();

                    handleSubmit(
                      e as unknown as React.FormEvent
                    );
                  }
                }}
                placeholder="Ask something about your documents..."
                rows={1}
                className="max-h-40 min-h-[56px] w-full resize-none bg-transparent px-4 py-4 pr-14 text-sm outline-none placeholder:text-zinc-400"
              />

              <button
                type="submit"
                disabled={!input.trim() || isLoading}
                className="absolute bottom-2.5 right-2.5 flex h-9 w-9 items-center justify-center rounded-lg bg-zinc-950 text-white transition hover:bg-zinc-800 disabled:cursor-not-allowed disabled:opacity-30"
              >
                <ArrowUp size={17} />
              </button>

            </div>

            <p className="mt-2 text-center text-[11px] text-zinc-400">
              Answers are generated from your uploaded documents.
            </p>

          </form>

        </div>

      </main>

    </div>
  );
}


interface MessageBubbleProps {
  message: Message;
}

function MessageBubble({
  message,
}: MessageBubbleProps) {
  const isUser = message.role === "user";

  return (
    <div
      className={`mb-8 flex ${
        isUser ? "justify-end" : "justify-start"
      }`}
    >

      <div
        className={
          isUser
            ? "max-w-[80%] rounded-2xl rounded-br-md bg-zinc-100 px-4 py-3 text-sm leading-6 text-white"
            : "w-full"
        }
      >

        {!isUser && (
          <div className="mb-3 flex items-center gap-2">

            <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-zinc-950 text-white">
              <Sparkles size={14} />
            </div>

            <span className="text-xs font-semibold text-zinc-700">
              Assistant
            </span>

          </div>
        )}

        <div className="whitespace-pre-wrap text-sm leading-7 text-zinc-800">
          {message.content}
        </div>

        {/* Sources */}
        {!isUser &&
          message.sources &&
          message.sources.length > 0 && (
            <Sources
              sources={message.sources}
            />
          )}

      </div>

    </div>
  );
}


interface SourcesProps {
  sources: Source[];
}

function Sources({ sources }: SourcesProps) {
  return (
    <div className="mt-5">

      <div className="mb-2 flex items-center gap-2">
        <div className="h-px flex-1 bg-zinc-200" />

        <span className="text-[11px] font-medium uppercase tracking-wider text-zinc-400">
          Sources
        </span>

        <div className="h-px flex-1 bg-zinc-200" />
      </div>

      <div className="grid gap-2 sm:grid-cols-2">

        {sources.map((source) => (
          <button
            key={source.id}
            type="button"
            className="group rounded-xl border border-zinc-200 bg-white p-3.5 text-left transition hover:border-zinc-300 hover:shadow-sm"
          >

            <div className="flex items-start gap-3">

              <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-zinc-100">
                <FileText
                  size={14}
                  className="text-zinc-500"
                />
              </div>

              <div className="min-w-0">

                <p className="truncate text-xs font-semibold text-zinc-700">
                  {source.filename}
                </p>

                {source.page && (
                  <p className="mt-0.5 text-[11px] text-zinc-400">
                    Page {source.page}
                  </p>
                )}

              </div>

            </div>

            {source.snippet && (
              <p className="mt-3 line-clamp-2 text-xs leading-5 text-zinc-500">
                {source.snippet}
              </p>
            )}

          </button>
        ))}

      </div>

    </div>
  );
}

function LoadingMessage() {
  return (
    <div className="mb-8 flex items-start gap-2">

      <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-zinc-950 text-white">
        <Sparkles size={14} />
      </div>

      <div className="flex items-center gap-1 rounded-xl bg-white px-4 py-3">

        <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-zinc-400" />

        <span
          className="h-1.5 w-1.5 animate-bounce rounded-full bg-zinc-400"
          style={{ animationDelay: "100ms" }}
        />

        <span
          className="h-1.5 w-1.5 animate-bounce rounded-full bg-zinc-400"
          style={{ animationDelay: "200ms" }}
        />

      </div>

    </div>
  );
}

